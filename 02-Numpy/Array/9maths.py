
import numpy as np
arr = np.array([10,20,30])

# -- mathematical operation 
print(arr + 5)
print(arr * 2)
print(arr ** 2)
print(arr / 10)



# Aggregation function (Summary)
print("\n",np.sum(arr))
print(np.mean(arr))
print(np.min(arr))
print(np.max(arr))
print(np.std(arr))   # -- standard
print(np.var(arr))
